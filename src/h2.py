# h2.py - structs + globals as hex
import os, sys
HEX = r'F:\study\projects\pirate-catalog\src'

def whex(lines):
    raw = '\n'.join(lines) + '\n'
    hexstr = raw.encode('utf-8').hex()
    with open(os.path.join(HEX, 'h2.hex'), 'w') as f:
        f.write(hexstr)
    print(f'h2: {len(raw)} chars -> {len(hexstr)} hex')

